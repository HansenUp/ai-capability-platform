"""Reviewed first-party offline compiler stage, called with an owned build context."""

import hashlib
import json
import os
import re
import shutil
import subprocess
import time
from pathlib import Path


def run_stage(*, base, project, vendor, root, tool, cargo_home, env, report, image):
    # Executed only by the owned orchestrator, not a third-party package.
    import signal

    frozen = json.loads((base / "build-inputs/native-build.json").read_text())
    for entry in frozen["tools"]:
        for key in ["path", "resolved"]:
            entry[key] = entry[key].replace("${HOME}", str(Path.home()))

    def sha_file(p):
        h = hashlib.sha256()
        with Path(p).open("rb") as f:
            for chunk in iter(lambda: f.read(1024**2), b""):
                h.update(chunk)
        return h.hexdigest()

    for t in frozen["tools"]:
        if sha_file(t["resolved"]) != t["sha256"]:
            raise ValueError("tool changed")
    ssl = Path("/private/etc/ssl/openssl.cnf")
    expected_ssl = "025f5e31cd7b2248a0a661d8d346452c31d98e280f3420c3f6017c74c829ae73"
    if sha_file(ssl) != expected_ssl:
        raise ValueError("SSL changed")
    for entry in frozen["compile_entries"]:
        folder = project if entry["name"] == "ai-platform-desktop-candidate" else vendor / (entry["name"] + "-" + entry["version"])
        for t in entry["targets"]:
            if sha_file(folder / t["source"]) != t["source_sha256"]:
                raise ValueError("entry source changed")
    # Fail before any compiler invocation if the known source has different byte views.
    check_source = vendor / "walkdir-2.5.0/compare/nftw.c"
    check_expected = "6b900b0ac78ce8ece1995f834b194fa14d87d744cabba8f475f0e10b21722c56"
    check_native = subprocess.run(  # noqa: S603 -- reviewed fixed tools/owned paths, bounded argument arrays, no shell
        ["/usr/bin/shasum", "-a", "256", str(check_source)], capture_output=True, text=True, check=True, timeout=10
    ).stdout.split()[0]
    report["cross_process_source_check"] = {"expected": check_expected, "python": sha_file(check_source), "native_shasum": check_native}
    if report["cross_process_source_check"]["python"] != check_expected or check_native != check_expected:
        raise ValueError("host source byte views differ; no build permitted; do not rewrite checksum")
    target = root / "target"
    target.mkdir()
    clt = Path("/Library/Developer/CommandLineTools")
    sdk = clt / "SDKs/MacOSX.sdk"
    execs = [t["resolved"] for t in frozen["tools"] if Path(t["path"]).name != "sandbox-exec"]
    ranlib = Path("/Library/Developer/CommandLineTools/usr/bin/ranlib")
    if (
        ranlib.resolve() != Path("/Library/Developer/CommandLineTools/usr/bin/libtool")
        or sha_file(ranlib) != "2840879786eb8868f03c3d378eef6c71d8416e15d8b14aebbf0c0cb80ad81c24"
    ):
        raise ValueError("ranlib tool changed")
    execs.extend([str(ranlib), str(ranlib.resolve())])
    report["additional_tool"] = {"path": str(ranlib), "resolved": str(ranlib.resolve()), "sha256": sha_file(ranlib)}
    profile = "(version 1)(deny default)(allow process-fork)(allow signal (target self))(allow sysctl-read)(allow file-read-metadata)\n"
    profile += "(allow process-exec " + " ".join("(literal " + json.dumps(p) + ")" for p in execs) + ")\n"
    # Only frozen package build-script output names are executable; the app binary is not.
    for entry in frozen["compile_entries"]:
        for build_target in entry["targets"]:
            if "custom-build" in build_target["kind"]:
                pattern = (
                    "^"
                    + re.escape(str(target))
                    + "/(aarch64-apple-darwin/)?debug/build/"
                    + re.escape(entry["name"])
                    + "-[0-9a-f]+/"
                    + re.escape(build_target["name"])
                    + "$"
                )
                profile += '(allow process-exec (regex #"' + pattern + '"))\n'
    profile += (
        '(allow file-read* (literal "/") (subpath "/System/Library") (subpath "/usr/lib") (subpath '
        + json.dumps(str(tool.parent))
        + ") (subpath "
        + json.dumps(str(clt))
        + ") (subpath "
        + json.dumps(str(root))
        + ') (literal "/dev/null") (literal "/dev/urandom") (literal "/dev/random"))\n'
    )
    for p in [target, cargo_home, root / "tmp", project / "gen", project / "permissions/autogenerated"]:
        p.mkdir(parents=True, exist_ok=True)
        profile += "(allow file-write* (subpath " + json.dumps(str(p)) + "))\n"
    profile += '(allow file-write* (literal "/dev/null"))(allow file-read-data (literal "/private/etc/ssl/openssl.cnf"))'
    (base / "g2-b-preflight/build-profile.sb").write_text(profile)
    env.update(
        {
            "SDKROOT": str(sdk),
            "CC": str(clt / "usr/bin/clang"),
            "AR": str(clt / "usr/bin/ar"),
            "CARGO_TARGET_AARCH64_APPLE_DARWIN_LINKER": str(clt / "usr/bin/clang"),
            "CARGO_TARGET_DIR": str(target),
        }
    )
    # Verify initialization under the actual injected build policy; fail before compile.
    for args in [[str(tool / "cargo"), "--version"], [str(tool / "rustc"), "-vV"]]:
        r = subprocess.run(  # noqa: S603 -- reviewed fixed tools/owned paths, bounded argument arrays, no shell
            ["/usr/bin/sandbox-exec", "-p", profile, *args], env=env, cwd=project, capture_output=True, text=True, timeout=20
        )
        if r.returncode:
            report["actual_policy_preflight_error"] = r.stderr
            raise ValueError("actual policy preflight failed")
    helper = target / "f8-synthetic-sidecar"
    helper_command = [
        str(tool / "rustc"),
        "--edition=2021",
        "--cfg",
        "f8_sidecar",
        "-C",
        "linker=" + str(clt / "usr/bin/clang"),
        str(project / "src/sidecar.rs"),
        "-o",
        str(helper),
    ]
    r = subprocess.run(  # noqa: S603 -- reviewed fixed tools/owned paths, bounded argument arrays, no shell
        ["/usr/bin/sandbox-exec", "-p", profile, *helper_command], env=env, cwd=project, capture_output=True, text=True, timeout=60
    )
    report["helper_compile"] = {"exit": r.returncode, "stderr": r.stderr}
    if r.returncode:
        raise ValueError("first-party helper compile failed")
    env["F8_SIDECAR_BINARY"] = str(helper)
    cmd = [
        str(tool / "cargo"),
        "build",
        "--frozen",
        "--offline",
        "--locked",
        "--jobs",
        "2",
        "--target",
        "aarch64-apple-darwin",
        "--manifest-path",
        str(project / "Cargo.toml"),
    ]
    report["build_command"] = cmd
    report["build_invocations"] = 1
    log = target / "build.log"
    owned = {}
    peak = 0
    began = time.monotonic()
    reason = None

    def snap():
        r = subprocess.run(["/bin/ps", "-axo", "pid=,ppid=,rss=,lstart="], capture_output=True, text=True, check=True, timeout=5)  # noqa: S603 -- reviewed fixed tools/owned paths, bounded argument arrays, no shell
        rows = {}
        for line in r.stdout.splitlines():
            v = line.split(None, 3)
            if len(v) == 4:
                rows[int(v[0])] = {"ppid": int(v[1]), "rss": int(v[2]) * 1024, "birth": v[3]}
        return rows

    with log.open("wb") as out:
        proc = subprocess.Popen(  # noqa: S603 -- reviewed fixed tools/owned paths, bounded argument arrays, no shell
            ["/usr/bin/sandbox-exec", "-p", profile, *cmd],
            env=env,
            cwd=project,
            stdout=out,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        try:
            while proc.poll() is None:
                rows = snap()
                ids = {proc.pid}
                changed = True
                while changed:
                    more = {pid for pid, v in rows.items() if v["ppid"] in ids}
                    changed = not more.issubset(ids)
                    ids |= more
                for pid in ids:
                    if pid in rows:
                        owned.setdefault(pid, rows[pid]["birth"])
                rss = sum(v["rss"] for pid, v in rows.items() if owned.get(pid) == v["birth"])
                peak = max(peak, rss)
                if rss > 4 * 1024**3:
                    reason = "RSS soft limit"
                if time.monotonic() - began > 3600:
                    reason = "wall limit"
                if image.stat().st_blocks * 512 + log.stat().st_size > 8 * 1024**3:
                    reason = "host disk limit"
                if log.stat().st_size > 32 * 1024**2:
                    reason = "log limit"
                if reason:
                    break
                time.sleep(0.1)
        finally:
            rows = snap()
            for pid, birth in sorted(owned.items(), key=lambda x: x[0] == proc.pid):
                if pid in rows and rows[pid]["birth"] == birth:
                    try:
                        os.kill(pid, signal.SIGTERM)
                    except ProcessLookupError:
                        pass
            if proc.poll() is None:
                try:
                    proc.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    reason = "process cleanup unknown"
    report["build_exit"] = proc.poll()
    report["stop_reason"] = reason
    report["peak_rss_bytes"] = peak
    report["build_seconds"] = round(time.monotonic() - began, 2)
    raw = log.read_bytes()
    (base / "g2-b-preflight/build-once.log").write_bytes(raw[: 32 * 1024**2])
    print(raw[-5000:].decode(errors="replace"), flush=True)
    remaining = snap()
    report["remaining_owned_pids"] = [pid for pid, birth in owned.items() if pid in remaining and remaining[pid]["birth"] == birth]
    if report["remaining_owned_pids"]:
        raise ValueError("owned process cleanup unknown")
    if sha_file(ssl) != expected_ssl:
        raise ValueError("SSL changed after build")
    if report.get("build_exit") == 0:
        artifact_dir = base / "artifacts"
        artifact_dir.mkdir(exist_ok=True)
        binary = target / "aarch64-apple-darwin/debug/ai-platform-desktop-candidate"
        output = artifact_dir / binary.name
        shutil.copy2(binary, output)
        report["artifact"] = {"path": str(output), "sha256": sha_file(output), "bytes": output.stat().st_size}
        helper_output = artifact_dir / helper.name
        shutil.copy2(helper, helper_output)
        report["helper_artifact"] = {"path": str(helper_output), "sha256": sha_file(helper_output), "bytes": helper_output.stat().st_size}
