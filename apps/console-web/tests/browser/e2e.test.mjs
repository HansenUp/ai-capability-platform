import test from "node:test";
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { apply, browser, phase, profile } from "./support.mjs";

test("隔离真实 Console/Runtime：创建→发布→同 Run 对话→他人审批→发起人输入补充", async () => {
  const tokens = JSON.parse(await readFile(profile.tokens, "utf8"));
  const engine = await browser();
  const context = await engine.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(5000);
  const mutations = [];
  page.on("request", request => {
    const path = new URL(request.url()).pathname;
    if (request.method() === "POST" && path.startsWith("/v1/")) mutations.push({ path, body: request.postDataJSON() });
  });
  const agent = `s12-e2e-${Date.now()}`;
  try {
    await page.goto(`${profile.url}/manage/agents`);
    await page.getByLabel("Agent ID", { exact: true }).fill(agent);
    await page.getByLabel("版本", { exact: true }).fill("1");
    await page.getByLabel("完整 config JSON（高级编辑，保留扩展字段）", { exact: true }).fill(JSON.stringify({ tools: ["ticket.close_batch"], user_input: true }));
    await page.getByRole("button", { name: "仅保存草稿", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "草稿已保存" }).waitFor();
    const row = page.getByRole("row").filter({ hasText: agent });
    assert.match(await row.innerText(), /draft/);
    await row.getByRole("button", { name: "评测与发布", exact: true }).click();
    await page.getByText("当前为开发 flag 模式，不会伪称 Langfuse 真实评测通过。", { exact: true }).waitFor();
    await page.getByLabel("显式确认开发态评测通过（非真实评测验收）", { exact: true }).check();
    await page.getByRole("button", { name: "检查并发布", exact: true }).click();
    await page.getByRole("heading", { name: "确认变更", exact: true }).waitFor();
    await page.getByRole("button", { name: "确认执行上述变更", exact: true }).click();
    await row.filter({ hasText: "published" }).waitFor();
    await page.goto(`${profile.url}/chat`);
    await apply(page, tokens.alice);
    await page.getByLabel("Agent ID", { exact: true }).fill(agent);
    await page.getByLabel("消息", { exact: true }).fill("S12_E2E_APPROVAL_THEN_INPUT");
    const registered = page.waitForResponse(response => new URL(response.url()).pathname === "/v1/workbench/create-attempts" && response.request().method() === "POST");
    await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).click();
    const registration = await registered; assert.equal(registration.status(), 200);
    const preparedCreate = await registration.json(), runId = preparedCreate.run_id;
    const created = page.waitForResponse(response => new URL(response.url()).pathname === `/v1/workbench/attempts/${preparedCreate.attempt_id}/execute`);
    await page.getByRole("button", { name: "确认执行已登记创建一次", exact: true }).click();
    const createResponse = await created; assert.equal(createResponse.status(), 200);
    assert.equal((await createResponse.json()).status, "COMMITTED");
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    await phase(page, runId, "auth-required", tokens.alice);
    await page.getByRole("button", { name: "跟随／续读已持久化事件", exact: true }).click();
    await page.getByRole("region", { name: "已持久化事件跟随" }).getByText(/tool.decision/).waitFor();
    await page.getByRole("button", { name: "停止本次只读刷新", exact: true }).click();
    await phase(page, runId, "auth-required", tokens.alice);
    await page.getByRole("button", { name: "预览批准", exact: true }).click();
    await page.getByRole("button", { name: "确认登记一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 403/).waitFor();
    assert.equal(await page.getByRole("heading", { name: "审批卡片：ticket.close_batch", exact: true }).count(), 0);
    await apply(page, tokens.bob);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByRole("button", { name: "预览批准", exact: true }).click();
    await page.getByRole("button", { name: "确认登记一次", exact: true }).click();
    await page.getByRole("button", { name: "确认执行已登记批准一次", exact: true }).click();
    await phase(page, runId, "input-required", tokens.bob);
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    await page.locator("section.card textarea").fill('{"id":"NOT-INITIATOR"}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 403/).waitFor();
    await apply(page, tokens.alice);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.locator("section.card textarea").fill('{"invalid":true}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 400/).waitFor();
    await apply(page, tokens.alice);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.locator("section.card textarea").fill('{"id":"SYNTHETIC-E2E"}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByRole("button", { name: "确认执行已登记回答一次", exact: true }).click();
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).waitFor();
    await phase(page, runId, "completed", tokens.alice);
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    const eventResponse = await page.request.get(`${profile.runtime}/v1/runs/${runId}/events`, { headers: { Authorization: `Bearer ${tokens.alice}` } });
    const events = await eventResponse.json();
    assert.equal(events.some(row => row.type === "model.response" && row.payload.text === "S12 自动端到端完成：仅合成工具，无外部效果。"), true,
      JSON.stringify(events.filter(row => row.type === "model.response").map(row => row.payload)));
    await page.getByText("助手：S12 自动端到端完成：仅合成工具，无外部效果。", { exact: true }).waitFor();
    assert.equal(events.filter(row => row.type === "tool.approved").length, 1);
    assert.equal(events.find(row => row.type === "tool.approved").payload.approver, "human:bob");
    assert.equal(events.filter(row => row.type === "tool.executed").length, 1);
    assert.equal(events.filter(row => row.type === "input.provided").length, 1);
    assert.equal(events.filter(row => row.type === "run.created").length, 1);
    assert.equal(events.find(row => row.type === "tool.result").payload.output.external_effect, false);
    await page.getByRole("button", { name: "跟随／续读已持久化事件", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "不推断 Run 完成" }).waitFor();
    assert.equal(await page.getByRole("region", { name: "已持久化事件跟随" }).locator("li").count(), events.length);
    assert.equal(await page.getByRole("region", { name: "已持久化事件跟随" }).getByText(/S12 自动端到端完成/).count(), 1);
    assert.equal(mutations.filter(row => row.path === "/v1/runs").length, 0);
    assert.equal(mutations.filter(row => row.path === "/v1/workbench/create-attempts").length, 1);
    assert.equal(mutations.some(row => row.path.endsWith("/resume")), false);
    assert.deepEqual(await page.evaluate(() => [localStorage.getItem("token"), sessionStorage.length]), [null, 0]);
    if (process.env.S12_BROWSER_EVIDENCE) {
      await page.screenshot({ path: `${process.env.S12_BROWSER_EVIDENCE}/completed.png`, fullPage: true });
      await writeFile(`${process.env.S12_BROWSER_EVIDENCE}/result.json`, JSON.stringify({ agent, run_id: runId,
        stages: ["created", "published", "auth-required", "input-required", "completed"], synthetic_writes: 1,
        approved_by: "human:bob", input_provided: 1, external_effect: false, profile: "local_flag_gate_mock_idp_policy_harness" }, null, 2));
    }
    await apply(page, tokens.foreign);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByText(/Runtime HTTP 404/).waitFor();
    assert.equal(await page.getByRole("heading", { name: new RegExp(runId) }).count(), 0);
  } finally { await context.close(); await engine.close(); }
});
