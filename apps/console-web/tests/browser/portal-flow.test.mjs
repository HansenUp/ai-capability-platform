import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { browser, phase, profile } from "./support.mjs";

test("隔离Portal：已发布目录→创建登记/执行/ACK→审批→输入→同Run事件与租户隔离", async () => {
  const tokens = JSON.parse(await readFile(profile.tokens, "utf8"));
  const engine = await browser();
  const context = await engine.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(5000);
  const mutations = [];
  page.on("request", request => {
    const path = new URL(request.url()).pathname;
    if (request.method() === "POST" && path.startsWith("/v1/")) mutations.push({ path, body: request.postDataJSON() });
  });
  const agent = "s12-workbench";
  await page.route("**/synthetic-tokens", route => route.fulfill({ json: tokens }));
  async function apply(page, token) {
    const actor = Object.keys(tokens).find(key => tokens[key] === token);
    await page.getByLabel("合成身份", { exact: true }).selectOption(actor);
    await page.getByRole("button", { name: "应用门户登录身份并核对账本", exact: true }).click();
    await page.getByRole("status").filter({ hasText: /验签身份与账本读取完成|已恢复服务端活动账本/ }).waitFor();
  }
  try {
    await page.goto(`${profile.url}/tests/browser/portal-flow.html`);
    await page.getByLabel("搜索 Agent", { exact: true }).fill(agent);
    await page.getByRole("link", { name: agent, exact: true }).click();
    await page.getByRole("region", { name: "任务体验指南", exact: true }).getByText(/未知写结果先只读恢复/).waitFor();
    await apply(page, tokens.alice);
    assert.equal(await page.getByLabel("Agent ID", { exact: true }).inputValue(), agent);
    await page.getByLabel("消息", { exact: true }).fill("S12_E2E_APPROVAL_THEN_INPUT");
    const registered = page.waitForResponse(response => new URL(response.url()).pathname === "/v1/workbench/create-attempts" && response.request().method() === "POST");
    await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).click();
    const registration = await registered; assert.equal(registration.status(), 200);
    const preparedCreate = await registration.json(), runId = preparedCreate.run_id;
    // Reload while PREPARED: only the authoritative ledger may restore the lock.
    await page.reload();
    await page.getByRole("link", { name: agent, exact: true }).click();
    await apply(page, tokens.alice_fresh);
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    assert.equal(await page.getByLabel("登记时的原始创建消息", { exact: true }).inputValue(), "");
    assert.equal(mutations.filter(row => row.path === "/v1/workbench/create-attempts").length, 1);
    await page.getByLabel("登记时的原始创建消息", { exact: true }).fill("S12_E2E_APPROVAL_THEN_INPUT");
    const executePath = `/v1/workbench/attempts/${preparedCreate.attempt_id}/execute`;
    await page.route(`**${executePath}`, async route => {
      // Commit on the temporary Runtime, then lose only the browser response.
      const committed = await route.fetch();
      assert.equal(committed.status(), 200);
      assert.equal((await committed.json()).status, "COMMITTED");
      await route.abort("failed");
    }, { times: 1 });
    await page.getByRole("button", { name: "确认执行已登记创建一次", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "结果未知" }).waitFor();
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    await apply(page, tokens.alice);
    await page.getByText(/状态 COMMITTED/).waitFor();
    assert.equal(mutations.filter(row => row.path === executePath).length, 1);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    await phase(page, runId, "auth-required", tokens.alice);
    await page.getByRole("button", { name: "跟随／续读已持久化事件", exact: true }).click();
    await page.getByRole("region", { name: "已持久化事件跟随" }).getByText(/tool.decision/).waitFor();
    await page.getByRole("button", { name: "停止本次只读刷新", exact: true }).click();
    await phase(page, runId, "auth-required", tokens.alice);
    await page.getByRole("button", { name: "预览批准", exact: true }).click();
    await page.getByRole("button", { name: "确认登记一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 403/).waitFor();
    assert.equal(await page.getByRole("heading", { name: "审批卡片：ticket.close_batch", exact: true }).count(), 0);
    await apply(page, tokens.bob);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByRole("button", { name: "预览批准", exact: true }).click();
    await page.getByRole("button", { name: "确认登记一次", exact: true }).click();
    await page.getByRole("button", { name: "确认执行已登记批准一次", exact: true }).click();
    await phase(page, runId, "input-required", tokens.bob);
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    await page.locator("section.card textarea").fill('{"id":"NOT-INITIATOR"}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 403/).waitFor();
    await apply(page, tokens.alice);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.locator("section.card textarea").fill('{"invalid":true}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByText(/Runtime HTTP 400/).waitFor();
    await apply(page, tokens.alice);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.locator("section.card textarea").fill('{"id":"SYNTHETIC-E2E"}');
    await page.getByRole("button", { name: "登记回答一次", exact: true }).click();
    await page.getByRole("button", { name: "确认执行已登记回答一次", exact: true }).click();
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).waitFor();
    await phase(page, runId, "completed", tokens.alice);
    assert.equal(await page.getByRole("button", { name: "登记新 Run（尚未创建）", exact: true }).isDisabled(), true);
    await page.getByRole("button", { name: "预览本人确认收口", exact: true }).click();
    await page.getByRole("button", { name: "确认收口此回执", exact: true }).click();
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find(button => button.textContent === "登记新 Run（尚未创建）")?.disabled);
    const eventResponse = await page.request.get(`${profile.runtime}/v1/runs/${runId}/events`, { headers: { Authorization: `Bearer ${tokens.alice}` } });
    const events = await eventResponse.json();
    assert.equal(events.some(row => row.type === "model.response" && row.payload.text === "S12 自动端到端完成：仅合成工具，无外部效果。"), true,
      JSON.stringify(events.filter(row => row.type === "model.response").map(row => row.payload)));
    await page.getByText("助手：S12 自动端到端完成：仅合成工具，无外部效果。", { exact: true }).waitFor();
    assert.equal(events.filter(row => row.type === "tool.approved").length, 1);
    assert.equal(events.find(row => row.type === "tool.approved").payload.approver, "human:bob");
    assert.equal(events.filter(row => row.type === "tool.executed").length, 1);
    assert.equal(events.filter(row => row.type === "input.provided").length, 1);
    assert.equal(events.filter(row => row.type === "run.created").length, 1);
    assert.equal(events.find(row => row.type === "tool.result").payload.output.external_effect, false);
    await page.getByRole("button", { name: "跟随／续读已持久化事件", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "不推断 Run 完成" }).waitFor();
    assert.equal(await page.getByRole("region", { name: "已持久化事件跟随" }).locator("li").count(), events.length);
    assert.equal(await page.getByRole("region", { name: "已持久化事件跟随" }).getByText(/S12 自动端到端完成/).count(), 1);
    assert.equal(mutations.filter(row => row.path === "/v1/runs").length, 0);
    assert.equal(mutations.filter(row => row.path === "/v1/workbench/create-attempts").length, 1);
    assert.equal(mutations.some(row => row.path.endsWith("/resume")), false);
    assert.deepEqual(await page.evaluate(() => [localStorage.getItem("token"), sessionStorage.length]), [null, 0]);
    // SSE deliberately clears the status snapshot; explicitly read state again.
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByRole("region", { name: "任务结果摘要" }).getByText(/Run 状态：completed/).waitFor();
    const writesBeforeTrace = mutations.length;
    const traceEntry = page.getByRole("button", { name: "查看此 Run 只读轨迹", exact: true });
    await traceEntry.focus(); await page.keyboard.press("Enter");
    assert.equal(await page.evaluate(() => document.activeElement?.id), "workbench-trace");
    const trace = page.getByRole("region", { name: "同 Run 只读轨迹", exact: true });
    assert.equal(await trace.getByRole("heading").innerText(), `执行轨迹 · ${runId}`);
    assert.equal(await trace.locator("li").count(), events.length);
    assert.equal(await trace.getByText(/工具结果 · tool.result/).count(), events.filter(row => row.type === "tool.result").length);
    assert.equal(mutations.length, writesBeforeTrace);
    await page.getByRole("button", { name: "读取本人 Run 首页", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "已读取本人当前 Agent 的 Run 记录" }).waitFor();
    const ownRow = page.getByRole("region", { name: "本人 Run 记录" }).getByRole("listitem").filter({ hasText: runId });
    await ownRow.getByRole("button", { name: "定位此 Run（尚未读取）", exact: true }).click();
    assert.equal(await page.getByLabel("Run ID", { exact: true }).inputValue(), runId);
    assert.equal(mutations.filter(row => row.path === "/v1/workbench/create-attempts").length, 1);
    const writesBeforeTasks = mutations.length;
    await page.getByRole("link", { name: "返回我的任务", exact: true }).click();
    await page.getByRole("button", { name: "应用身份并读取任务首页", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "本人任务已读取" }).waitFor();
    await page.getByLabel("任务 Agent 筛选", { exact: true }).fill(agent);
    await page.getByLabel("任务状态", { exact: true }).selectOption("completed");
    assert.equal(await page.getByRole("link", { name: `查看任务 ${runId}`, exact: true }).count(), 0);
    await page.getByRole("button", { name: "应用身份并读取任务首页", exact: true }).click();
    await page.getByRole("link", { name: `查看任务 ${runId}`, exact: true }).click();
    await apply(page, tokens.alice);
    await page.getByRole("button", { name: "定位链接中的 Run（尚未读取）", exact: true }).click();
    assert.equal(await page.getByLabel("Run ID", { exact: true }).inputValue(), runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByRole("region", { name: "同 Run 只读轨迹", exact: true }).getByRole("heading").waitFor();
    assert.equal(mutations.length, writesBeforeTasks);
    await apply(page, tokens.foreign);
    await page.getByLabel("Run ID", { exact: true }).fill(runId);
    await page.getByRole("button", { name: "读取 Run 与待办卡片", exact: true }).click();
    await page.getByText(/Runtime HTTP 404/).waitFor();
    assert.equal(await page.getByRole("heading", { name: new RegExp(runId) }).count(), 0);
    assert.equal(await page.getByRole("region", { name: "任务结果摘要" }).count(), 0);
    assert.equal(await page.getByRole("region", { name: "同 Run 只读轨迹", exact: true }).count(), 0);
    const writesBeforeEmbed = mutations.length;
    await page.goto(`${profile.url}/tests/browser/sdk-host.html?run=${encodeURIComponent(runId)}`);
    await page.getByText(`Run ${runId} · completed`, { exact: true }).waitFor();
    assert.equal(await page.locator("#events li").count(), events.length);
    assert.equal(mutations.length, writesBeforeEmbed);
    assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0, 0]);
  } finally { await context.close(); await engine.close(); }
});
